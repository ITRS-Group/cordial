package certs

import (
	"crypto"
	"crypto/ecdh"
	"crypto/ecdsa"
	"crypto/ed25519"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/rsa"
	"crypto/x509"
	"errors"
	"fmt"
	"os"
	"strings"
)

// KeyType identifies the type of private key to generate. The supported
// values are "rsa", "ecdsa", "ed25519" and "ecdh".
//
// X.509 certificates need a key that can sign, and an ECDH key cannot.
// To keep "ecdh" usable everywhere a key type is accepted, a key of type
// [ECDH] is generated as an ECDSA P-256 key, which has exactly the same
// curve and PKCS#8 encoding as an ECDH P-256 key. This means that a
// parsed key will report its type as [ECDSA] and not [ECDH]. Only a
// genuine X25519 key (which cannot be generated by this package) is
// parsed as [ECDH] and such keys cannot be used to sign certificates.
type KeyType string

// PrivateKey is a DER encoded private key, normally PKCS#8, but PKCS#1
// (RSA) and SEC1 (EC) encodings are also accepted when parsing.
type PrivateKey []byte

const (
	// RSA is a 4096-bit RSA key.
	RSA KeyType = "rsa"
	// ECDSA is an ECDSA key on the P-256 curve.
	ECDSA KeyType = "ecdsa"
	// ED25519 is an Ed25519 key. These are not supported by most web
	// browsers.
	ED25519 KeyType = "ed25519"
	// ECDH is accepted for compatibility and generates an ECDSA P-256
	// key, see [KeyType].
	ECDH KeyType = "ecdh"
)

// DefaultKeyType is the default key type. It is "ecdh" for
// compatibility with existing configurations and, as described for
// [KeyType], results in an ECDSA P-256 key.
const DefaultKeyType = ECDH

// String returns the key type as a string.
func (k *KeyType) String() string {
	return string(*k)
}

// Set sets the key type from a case-insensitive string, for use as a
// flag value. It returns an error if the string is not a supported key
// type.
func (k *KeyType) Set(s string) error {
	kt := strings.ToLower(s)
	switch kt {
	case "rsa", "ecdsa", "ed25519", "ecdh":
		*k = KeyType(kt)
		return nil
	default:
		return fmt.Errorf("invalid key type %q, must be one of rsa, ecdsa, ed25519 or ecdh", s)
	}
}

// Type returns the name of the flag value type.
func (k *KeyType) Type() string {
	return "KeyType"
}

// GenerateKey returns a PKCS#8 DER encoded private key using the
// keyType specified, and the corresponding public key. The key can
// always be used to sign certificates; see [KeyType] for how the
// [ECDH] key type is handled.
func GenerateKey(keyType KeyType) (privateKey PrivateKey, publicKey any, err error) {
	var pKey crypto.Signer

	switch keyType {
	case RSA:
		pKey, err = rsa.GenerateKey(rand.Reader, 4096)
	case ECDSA, ECDH:
		pKey, err = ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	case ED25519:
		_, pKey, err = ed25519.GenerateKey(rand.Reader)
	default:
		err = fmt.Errorf("%w unsupported key type %s", os.ErrInvalid, keyType)
	}
	if err != nil {
		return
	}

	key, err := x509.MarshalPKCS8PrivateKey(pKey)
	if err != nil {
		return
	}

	return PrivateKey(key), pKey.Public(), nil
}

// ParsePrivateKey parses the DER encoded private key enclave, first as
// PKCS#8 and then as a PKCS#1 and finally as SEC1 (EC) if that fails.
// It returns the private key or an error.
//
// P-256 keys are reported as [ECDSA], see [KeyType].
func ParsePrivateKey(key PrivateKey) (privatekey any, keytype KeyType, err error) {
	if key == nil {
		err = fmt.Errorf("no key provided")
		return
	}
	privatekey, err8 := x509.ParsePKCS8PrivateKey(key)
	if err8 != nil {
		var err1, err2 error
		if privatekey, err1 = x509.ParsePKCS1PrivateKey(key); err1 != nil {
			if privatekey, err2 = x509.ParseECPrivateKey(key); err2 != nil {
				return nil, "", fmt.Errorf("cannot parse private key as PKCS#8, PKCS#1 or SEC1: %w", errors.Join(err8, err1, err2))
			}
		}
	}

	switch privatekey.(type) {
	case *rsa.PrivateKey:
		keytype = RSA
	case *ecdsa.PrivateKey:
		keytype = ECDSA
	case *ecdh.PrivateKey:
		keytype = ECDH
	case ed25519.PrivateKey: // not a pointer
		keytype = ED25519
	default:
		return nil, "", fmt.Errorf("unsupported private key type %T", privatekey)
	}
	return
}

// toPKCS8 returns the key as PKCS#8 DER, converting from PKCS#1 or SEC1
// if required. Keys that are already PKCS#8 are returned unchanged.
func toPKCS8(key PrivateKey) (PrivateKey, error) {
	priv, _, err := ParsePrivateKey(key)
	if err != nil {
		return nil, err
	}
	if _, err := x509.ParsePKCS8PrivateKey(key); err == nil {
		return key, nil
	}
	der, err := x509.MarshalPKCS8PrivateKey(priv)
	if err != nil {
		return nil, err
	}
	return PrivateKey(der), nil
}

// PublicKey parses the DER encoded private key enclave and returns the
// public key if successful. It will first try as PKCS#8 and then PKCS#1
// if that fails and finally as SEC1 (EC). Returns an error if parsing
// fails.
func PublicKey(key PrivateKey) (publicKey crypto.PublicKey, err error) {
	if key == nil {
		err = fmt.Errorf("no key provided")
		return
	}
	privateKey, _, err := ParsePrivateKey(key)
	if err != nil {
		return
	}

	switch k := privateKey.(type) {
	case crypto.Signer:
		publicKey = k.Public()
	case *ecdh.PrivateKey:
		publicKey = k.PublicKey()
	default:
		err = fmt.Errorf("unsupported private key type %T", privateKey)
	}

	return
}

// IndexPrivateKey tests the slice DER encoded private keys against the x509
// cert and returns the index of the first match, or -1 if none of the
// keys match.
func IndexPrivateKey(keys []PrivateKey, cert *x509.Certificate) int {
	if cert == nil {
		return -1
	}

	for i, key := range keys {
		if pubkey, err := PublicKey(key); err == nil { // if ok then compare
			// ensure we have an Equal() method on the opaque key
			if k, ok := pubkey.(interface{ Equal(crypto.PublicKey) bool }); ok {
				if k.Equal(cert.PublicKey) {
					return i
				}
			}
		}
	}
	return -1
}

// CheckKeyMatch returns true if the DER encoded private key matches
// the public key in the provided x509 certificate.
func CheckKeyMatch(key PrivateKey, cert *x509.Certificate) bool {
	pubkey, err := PublicKey(key)
	if err != nil {
		return false
	}
	// ensure we have an Equal() method on the opaque key
	if k, ok := pubkey.(interface{ Equal(crypto.PublicKey) bool }); ok {
		return k.Equal(cert.PublicKey)
	}
	return false
}
